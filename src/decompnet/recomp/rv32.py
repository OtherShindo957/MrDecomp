"""Small verified RV32I subset -> C, for raw redistributable test programs.

Contract: little-endian words loaded at PC 0; x10/a0 is the input and result;
64 KiB unified memory, code is read-only; no OS, ELF, relocations, or console services.
Only the enumerated instructions are accepted. EBREAK terminates this test harness.
"""
from __future__ import annotations

import json
import platform
import shutil
import struct
import subprocess
from dataclasses import dataclass, asdict
from pathlib import Path

SUPPORTED = ('ADDI', 'ADD', 'SUB', 'XOR', 'OR', 'AND', 'LUI', 'BEQ', 'BNE', 'JAL', 'LW', 'SW', 'EBREAK')
MAX_CODE = 4096
MEMORY_SIZE = 65536
MAX_STEPS = 100000


class TranslationError(ValueError):
    pass


@dataclass(frozen=True)
class Instruction:
    pc: int
    word: int
    op: str
    rd: int = 0
    rs1: int = 0
    rs2: int = 0
    imm: int = 0


def signed(value: int, bits: int) -> int:
    return value - (1 << bits) if value & (1 << (bits - 1)) else value


def decode(code: bytes) -> list[Instruction]:
    if not code or len(code) % 4 or len(code) > MAX_CODE:
        raise TranslationError('Raw RV32 input must contain 1–1024 aligned 32-bit instructions (at most 4096 bytes)')
    result = []
    for pc in range(0, len(code), 4):
        word = int.from_bytes(code[pc:pc + 4], 'little')
        opcode, rd, f3, rs1, rs2, f7 = word & 127, (word >> 7) & 31, (word >> 12) & 7, (word >> 15) & 31, (word >> 20) & 31, word >> 25
        op, imm = None, 0
        if word == 0x00100073:
            op = 'EBREAK'
        elif opcode == 0x13 and f3 == 0:
            op, imm = 'ADDI', signed(word >> 20, 12)
        elif opcode == 0x33:
            op = {(0, 0): 'ADD', (0, 32): 'SUB', (4, 0): 'XOR', (6, 0): 'OR', (7, 0): 'AND'}.get((f3, f7))
        elif opcode == 0x37:
            op, imm = 'LUI', word & 0xfffff000
        elif opcode == 0x63 and f3 in (0, 1):
            op = 'BEQ' if f3 == 0 else 'BNE'
            imm = signed(((word >> 31) << 12) | (((word >> 7) & 1) << 11) | (((word >> 25) & 63) << 5) | (((word >> 8) & 15) << 1), 13)
        elif opcode == 0x6f:
            op = 'JAL'
            imm = signed(((word >> 31) << 20) | (((word >> 12) & 255) << 12) | (((word >> 20) & 1) << 11) | (((word >> 21) & 1023) << 1), 21)
        elif opcode == 0x03 and f3 == 2:
            op, imm = 'LW', signed(word >> 20, 12)
        elif opcode == 0x23 and f3 == 2:
            op, imm = 'SW', signed(((word >> 25) << 5) | ((word >> 7) & 31), 12)
        if op is None:
            raise TranslationError(f'Unsupported instruction 0x{word:08x} at PC 0x{pc:08x}')
        if op in ('BEQ', 'BNE', 'JAL') and (not 0 <= pc + imm < len(code) or (pc + imm) % 4):
            raise TranslationError(f'{op} at PC 0x{pc:08x} targets an unaligned or out-of-range address')
        result.append(Instruction(pc, word, op, rd, rs1, rs2, imm))
    return result


def translate(code: bytes) -> tuple[str, list[dict]]:
    instructions = decode(code)
    cases = []
    for i in instructions:
        a, b = f'r[{i.rs1}]', f'r[{i.rs2}]'
        next_pc = i.pc + 4
        operation = ''
        if i.op == 'EBREAK':
            operation = 'state = "halted"; goto done;'
        elif i.op == 'ADDI':
            operation = f'r[{i.rd}] = {a} + UINT32_C({i.imm & 0xffffffff});'
        elif i.op in ('ADD', 'SUB', 'XOR', 'OR', 'AND'):
            operator = {'ADD': '+', 'SUB': '-', 'XOR': '^', 'OR': '|', 'AND': '&'}[i.op]
            operation = f'r[{i.rd}] = {a} {operator} {b};'
        elif i.op == 'LUI':
            operation = f'r[{i.rd}] = UINT32_C({i.imm});'
        elif i.op in ('BEQ', 'BNE'):
            operation = f'pc = ({a} {"==" if i.op == "BEQ" else "!="} {b}) ? {i.pc + i.imm}u : {next_pc}u;'
        elif i.op == 'JAL':
            operation = f'r[{i.rd}] = {next_pc}u; pc = {i.pc + i.imm}u;'
        elif i.op in ('LW', 'SW'):
            operation = f'addr = {a} + UINT32_C({i.imm & 0xffffffff});\n'
            operation += 'if ((addr & 3u) || addr > sizeof(mem) - 4u) { state = "memory-trap"; goto done; }\n'
            if i.op == 'LW':
                operation += f'r[{i.rd}] = (uint32_t)mem[addr] | ((uint32_t)mem[addr+1] << 8) | ((uint32_t)mem[addr+2] << 16) | ((uint32_t)mem[addr+3] << 24);'
            else:
                operation += f'if (addr < {len(code)}u) {{ state = "code-write-trap"; goto done; }}\n'
                operation += f'for (unsigned j=0; j<4; j++) mem[addr+j] = (uint8_t)({b} >> (j*8));'
        if i.op not in ('BEQ', 'BNE', 'JAL', 'EBREAK'):
            operation += f' pc = {next_pc}u;'
        cases.append(f'case {i.pc}u: /* {i.op} 0x{i.word:08x} */\n{operation}\nr[0] = 0; break;')
    source = '''/* Generated by MrDecomp's experimental RV32I subset translator.
   No runtime instruction decoding. No host calls from guest code. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <inttypes.h>
int main(int argc, char **argv) {
    uint32_t r[32] = {0}, pc = 0, addr = 0, steps = 0;
    uint8_t mem[65536] = {CODE};
    const char *state = "step-limit";
    if (argc > 1) r[10] = (uint32_t)strtoull(argv[1], NULL, 10);
    while (steps < 100000u) {
        steps++;
        switch (pc) {
CASES
        default: state = "pc-trap"; goto done;
        }
    }
done:
    r[0] = 0;
    printf("{\\"state\\":\\"%s\\",\\"pc\\":%" PRIu32 ",\\"steps\\":%" PRIu32 ",\\"registers\\":[", state, pc, steps);
    for (unsigned n=0; n<32; n++) printf("%s%" PRIu32, n ? "," : "", r[n]);
    puts("]}");
    return 0;
}
'''.replace('CODE', ','.join(str(b) for b in code)).replace('CASES', '\n'.join(cases))
    return source, [asdict(i) for i in instructions]


def build_and_run(code: bytes, root: Path, argument: int = 10, log=print) -> dict:
    if not isinstance(argument, int) or isinstance(argument, bool) or not 0 <= argument <= 0xffffffff:
        raise TranslationError('a0 input must be an unsigned 32-bit integer')
    if platform.system() != 'Linux' or platform.machine().lower() not in ('x86_64', 'amd64'):
        raise TranslationError('Native execution is currently verified only on Linux AMD64')
    cc = shutil.which('cc')
    if not cc:
        raise TranslationError('A C compiler (cc) is required for this experiment')
    source, instructions = translate(code)
    # Callers provide a new experiment directory. Never overwrite a previous result or user file.
    root.mkdir(parents=True, exist_ok=False)
    (root / 'input.rv32').write_bytes(code)
    (root / 'translated.c').write_text(source, encoding='utf-8')
    log(f'Decoded and statically translated {len(instructions)} instructions')
    log('Compiling translated C for the native host')
    command = [cc, '-std=c11', '-O2', '-Wall', '-Wextra', str(root / 'translated.c'), '-o', str(root / 'program')]
    try:
        build = subprocess.run(command, capture_output=True, text=True, timeout=30)
        if build.returncode:
            raise TranslationError(f'C compilation failed ({build.returncode}): {build.stderr[-4000:]}')
        log('Executing translated program with a 100000-instruction bound')
        run = subprocess.run([str(root / 'program'), str(argument)], capture_output=True, text=True, timeout=5)
        if run.returncode:
            raise TranslationError(f'Native execution failed ({run.returncode}): {run.stderr[-4000:]}')
        execution = json.loads(run.stdout)
    except TranslationError:
        raise
    except subprocess.TimeoutExpired as e:
        raise TranslationError(f'{"Compilation" if e.timeout == 30 else "Execution"} timed out') from e
    except (ValueError, KeyError) as e:
        raise TranslationError('Invalid native harness result') from e
    result = {'backend': 'rv32i-subset', 'target': 'linux-amd64', 'output': str(root),
              'source': source, 'instructions': instructions, 'execution': execution,
              'compiler_diagnostics': build.stderr[-4000:], 'success': execution['state'] == 'halted'}
    (root / 'result.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    log(f"Execution state: {execution['state']}; a0={execution['registers'][10]}; steps={execution['steps']}")
    if not result['success']:
        raise TranslationError(f"Translated program stopped with {execution['state']} at PC 0x{execution['pc']:08x}; diagnostics saved in {root}")
    return result


def demo_program() -> bytes:
    """CC0 test fixture: sum 1..a0, storing/loading the result in guest memory at 4096."""
    words = [0x00050093,  # addi x1, a0, 0
             0x00000513,  # addi a0, x0, 0
             0x00008863,  # beq x1, x0, +16
             0x00150533,  # add a0, a0, x1
             0xfff08093,  # addi x1, x1, -1
             0xff5ff06f,  # jal x0, -12
             0x00001137,  # lui x2, 1
             0x00a12023,  # sw a0, 0(x2)
             0x00012503,  # lw a0, 0(x2)
             0x00100073]  # ebreak (harness stop)
    return struct.pack('<' + 'I' * len(words), *words)
